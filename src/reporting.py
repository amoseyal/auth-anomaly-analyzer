def escape_html_value(value):
    '''
    Convert a value into HTML-safe text.

    Escapes special HTML characters so authentication log data
    is displayed as text rather than interpreted as markup.
    '''

    # Convert values such as integers and pandas timestamps
    # into strings before applying HTML escaping.
    return escape(str(value), quote=True)


def get_authentication_status_class(status):
    '''
    Return a recognized CSS class for an authentication status.

    Only explicitly supported authentication outcomes may be
    used as status-specific CSS classes.
    '''

    # Define the authentication outcomes supported by the report.
    allowed_statuses = {
        'success',
        'failure'
    }

    # Return the original status only when it is recognized.
    if status in allowed_statuses:
        return status

    # Assign a neutral class to unexpected authentication statuses.
    return 'unknown'


def build_detection_evidence(alert):
    '''
    Prepare human-readable evidence fields for a security alert.

    The function uses evidence already produced by the detection
    engine. It does not recalculate or modify detection results.
    '''

    # Include evidence fields common to all current detections.
    evidence = {
        'Severity': alert.get('severity', 'unknown').title(),
        'Source IP': alert.get('source_ip', 'Not available'),
        'Detection Window': alert.get('window', 'Not available')
    }

    # Add evidence specific to brute-force detections.
    if alert['detection'] == 'brute_force':

        evidence['Target Account'] = alert.get(
            'username',
            'Not available'
        )

        evidence['Failed Attempts'] = alert.get(
            'failure_count',
            'Not available'
        )

    # Add evidence specific to password-spraying detections.
    elif alert['detection'] == 'password_spraying':

        evidence['Accounts Targeted'] = alert.get(
            'unique_user_count',
            'Not available'
        )

        evidence['Targeted Usernames'] = ', '.join(
            alert.get('usernames', [])
        )

    # Add evidence specific to successful logins following failures.
    elif alert['detection'] == 'success_after_failures':

        evidence['Target Account'] = alert.get(
            'username',
            'Not available'
        )

        evidence['Preceding Failures'] = alert.get(
            'failure_count',
            'Not available'
        )

        evidence['Successful Login'] = alert.get(
            'success_time',
            'Not available'
        )

    # Include the observed failure timestamps when available.
    evidence['First Failure'] = alert.get(
        'first_failure',
        'Not available'
    )

    evidence['Last Failure'] = alert.get(
        'last_failure',
        'Not available'
    )

    return evidence

